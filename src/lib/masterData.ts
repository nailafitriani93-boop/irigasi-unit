import type {
  ParsedExcelSheet,
  ParsedExcelWorkbook,
} from "@/data/xlsxLite";
import type { AreaScope } from "@/data/userData";
import { db } from "@/lib/db";
import { isAreaScope } from "@/lib/areaAccess";
import type { EquipmentRecord } from "@/lib/irrigationEquipment";

export type MasterDataVersion = {
  id: string;
  dataset_year: number;
  revision: number;
  original_filename: string;
  uploaded_by: string;
  uploaded_at: string;
  is_active: boolean;
};

export type MasterDataSnapshot = MasterDataVersion & {
  workbook_data: ParsedExcelWorkbook;
};

const MASTER_DATA_SCHEMA = `
  CREATE TABLE IF NOT EXISTS public.irrigation_master_data_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_year INTEGER NOT NULL CHECK (dataset_year BETWEEN 2000 AND 2100),
    revision INTEGER NOT NULL CHECK (revision > 0),
    original_filename TEXT NOT NULL,
    uploaded_by TEXT NOT NULL,
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    workbook_bytes BYTEA NOT NULL,
    workbook_data JSONB NOT NULL,
    CONSTRAINT irrigation_master_data_year_revision_key
      UNIQUE (dataset_year, revision)
  );
  CREATE UNIQUE INDEX IF NOT EXISTS irrigation_master_data_one_active_idx
    ON public.irrigation_master_data_versions (is_active)
    WHERE is_active = TRUE;
`;

let masterDataSchemaPromise: Promise<void> | null = null;

export async function ensureMasterDataTable() {
  if (!masterDataSchemaPromise) {
    masterDataSchemaPromise = db
      .query(MASTER_DATA_SCHEMA)
      .then(() => undefined)
      .catch((error: unknown) => {
        masterDataSchemaPromise = null;
        throw error;
      });
  }
  await masterDataSchemaPromise;
}

export async function getMasterDataVersions() {
  await ensureMasterDataTable();
  const result = await db.query<MasterDataVersion>(
    `SELECT
       id::text AS id,
       dataset_year,
       revision,
       original_filename,
       uploaded_by,
       uploaded_at::text AS uploaded_at,
       is_active
     FROM public.irrigation_master_data_versions
     ORDER BY dataset_year DESC, revision DESC`,
  );
  return result.rows;
}

export async function getMasterDataSnapshot(
  year?: number,
): Promise<MasterDataSnapshot | null> {
  await ensureMasterDataTable();
  const result = year === undefined
    ? await db.query<MasterDataSnapshot>(
        `SELECT
           id::text AS id,
           dataset_year,
           revision,
           original_filename,
           uploaded_by,
           uploaded_at::text AS uploaded_at,
           is_active,
           workbook_data
         FROM public.irrigation_master_data_versions
         WHERE is_active = TRUE
         LIMIT 1`,
      )
    : await db.query<MasterDataSnapshot>(
        `SELECT
           id::text AS id,
           dataset_year,
           revision,
           original_filename,
           uploaded_by,
           uploaded_at::text AS uploaded_at,
           is_active,
           workbook_data
         FROM public.irrigation_master_data_versions
         WHERE dataset_year = $1
         ORDER BY revision DESC
         LIMIT 1`,
        [year],
      );
  return result.rows[0] ?? null;
}

function isObject(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

export function validateParsedWorkbook(
  value: unknown,
): ParsedExcelWorkbook | null {
  if (!isObject(value)) return null;

  const workbook: ParsedExcelWorkbook = {};
  for (const [sheetName, rawSheet] of Object.entries(value)) {
    if (!isObject(rawSheet) || !Array.isArray(rawSheet.rows) || !isObject(rawSheet.cells)) {
      return null;
    }

    const cells: Record<string, string | number> = {};
    for (const [address, cell] of Object.entries(rawSheet.cells)) {
      if (!/^[A-Z]+[1-9]\d*$/.test(address)) return null;
      if (typeof cell !== "string" && (typeof cell !== "number" || !Number.isFinite(cell))) {
        return null;
      }
      cells[address] = cell;
    }

    const rows: ParsedExcelSheet["rows"] = [];
    for (const rawRow of rawSheet.rows) {
      if (!isObject(rawRow) || !Number.isSafeInteger(rawRow.rowNumber) || Number(rawRow.rowNumber) < 1 || !isObject(rawRow.values)) {
        return null;
      }

      const rowValues: Record<string, string> = {};
      for (const [header, cell] of Object.entries(rawRow.values)) {
        if (typeof cell !== "string") return null;
        rowValues[header] = cell;
      }
      rows.push({ rowNumber: Number(rawRow.rowNumber), values: rowValues });
    }

    workbook[sheetName] = { rows, cells };
  }

  return workbook;
}

export function parseEquipmentRecords(
  workbook: ParsedExcelWorkbook,
): EquipmentRecord[] {
  const sheetConfigurations = [
    {
      sheet: "EngineIrigasi",
      type: "Engine",
      codeField: "Kode Engine",
      groupField: "Sumber Air",
      statusField: "Kondisi Engine",
    },
    {
      sheet: "IrigatorIrigasi",
      type: "Irrigator",
      codeField: "Kode Irigator",
      groupField: "Tipe Irigator",
      statusField: "Kondisi Irigator",
    },
  ] as const;
  const records: EquipmentRecord[] = [];

  for (const configuration of sheetConfigurations) {
    const sheet = workbook[configuration.sheet];
    if (!sheet) throw new Error(`Sheet ${configuration.sheet} tidak ditemukan.`);

    const seenCodes = new Set<string>();
    for (const row of sheet.rows) {
      const code = row.values[configuration.codeField]?.trim() ?? "";
      if (!code) continue;

      const area = row.values.Area?.trim() ?? "";
      if (!isAreaScope(area) || area === "PG1") {
        throw new Error(
          `Area tidak valid untuk aset ${code} pada baris ${row.rowNumber}.`,
        );
      }
      if (seenCodes.has(code.toLowerCase())) {
        throw new Error(`Kode aset ${code} tercantum lebih dari satu kali.`);
      }
      seenCodes.add(code.toLowerCase());

      const fields = { ...row.values };
      const group = fields[configuration.groupField]?.trim() ?? "";
      if (!group) {
        throw new Error(
          `Kelompok aset untuk ${code} kosong pada baris ${row.rowNumber}.`,
        );
      }
      records.push({
        sheet: configuration.sheet,
        type: configuration.type,
        row: row.rowNumber,
        code,
        group,
        area,
        status: fields[configuration.statusField]?.trim() ?? "",
        note: fields.Keterangan?.trim() ?? "",
        fields,
      });
    }

    if (!seenCodes.size) {
      throw new Error(`Tidak ada data aset valid pada sheet ${configuration.sheet}.`);
    }
  }

  return records;
}

export function equipmentRecordsFromSnapshot(
  snapshot: MasterDataSnapshot,
  areaScope: AreaScope,
) {
  const records = parseEquipmentRecords(snapshot.workbook_data);
  return areaScope === "PG1"
    ? records
    : records.filter((record) => record.area === areaScope);
}
